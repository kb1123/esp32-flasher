// ===== siggen.h: three PWM-based signal outputs =====
#pragma once
#include <Arduino.h>
#include "wavecore.h"

namespace siggen {

constexpr int N = 3;

struct Output {
  int pin;          // GPIO
  int header;       // pin number on the 40-pin header
  bool available;   // false when the pin is taken (e.g. IO17 used for the motor STEP)
};

// pins[i] / avail[i]: configured once at boot. saved: power-on settings.
bool begin(const Output outs[N], const wave::Settings saved[N]);
bool set(int i, const wave::Settings &s, bool resyncAfter);   // false if that output is unavailable
wave::Settings get(int i);
const Output &output(int i);
bool hardwareSquare(int i);       // square generated by its LEDC timer (exact edges)
double actualHz(int i);           // what the hardware is really producing
void resync();                    // restart every output at its phase offset, together

}  // namespace siggen
